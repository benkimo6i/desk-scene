// Writes src/zones.js: every timezone's reference point (lat, lon to a tenth of a degree),
// from the tz database's zone.tab. The city matcher uses it to break ties between cities
// that share a UTC offset. Run: node scripts/make-zones.mjs [path/to/zone.tab]
import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2] ?? '/usr/share/zoneinfo/zone.tab';
// ISO 6709: +DDMM or +DDMMSS for latitude, +DDDMM or +DDDMMSS for longitude.
const degrees = (text, width) => {
  const sign = text[0] === '-' ? -1 : 1;
  const [d, m, s] = text.slice(1).match(new RegExp(`^(\\d{${width}})(\\d\\d)(\\d\\d)?$`)).slice(1).map((v) => Number(v ?? 0));
  return Math.round(sign * (d + m / 60 + s / 3600) * 10) / 10;
};
const lines = readFileSync(source, 'utf8').split('\n').filter((l) => l && !l.startsWith('#'));
const zones = lines.map((line) => {
  const [, coords, name] = line.split('\t');
  const [, lat, lon] = coords.match(/^([+-]\d+)([+-]\d+)$/);
  return `${name} ${degrees(lat, 2)} ${degrees(lon, 3)}`;
}).sort();

writeFileSync(new URL('../src/zones.js', import.meta.url), `// Generated by scripts/make-zones.mjs from the tz database's zone.tab. Do not edit.
// One timezone per line: name, latitude, longitude.
export default \`${zones.join('\n')}\`;
`);
console.log(`${zones.length} zones`);
